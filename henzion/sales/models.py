from django.conf import settings
from django.db import models
from django.utils import timezone

from core.constants import SALE_METHOD_CHOICES, SALE_METHODS


class Neighbor(models.Model):
    """A nearby shop the cashier fetches items from when we don't stock what the customer wants."""

    name = models.CharField(max_length=120)
    phone = models.CharField(max_length=30, blank=True)
    shop = models.CharField("Shop / location", max_length=120, blank=True)
    notes = models.CharField(max_length=200, blank=True)
    created_at = models.DateTimeField(auto_now_add=True)

    class Meta:
        ordering = ["name"]

    def __str__(self):
        return self.name


class Sale(models.Model):
    COMPLETED = "completed"
    CANCELLED = "cancelled"
    STATUS_CHOICES = [(COMPLETED, "Completed"), (CANCELLED, "Cancelled")]

    number = models.CharField(max_length=20, blank=True, db_index=True)
    # Generated by the browser so a double-click / retry can never create the sale twice.
    client_uuid = models.UUIDField(null=True, blank=True, unique=True)
    date = models.DateField(default=timezone.localdate)
    due_date = models.DateField(null=True, blank=True)

    customer_name = models.CharField(max_length=120, blank=True)
    customer_phone = models.CharField(max_length=30, blank=True)
    customer_address = models.CharField(max_length=200, blank=True)
    customer_niu = models.CharField(max_length=40, blank=True)

    # Summary of how it was paid: one method, or "split". The real breakdown is in SalePayment.
    payment_method = models.CharField(max_length=14, choices=SALE_METHOD_CHOICES)
    payment_reference = models.CharField("Mobile money reference", max_length=60, blank=True)
    notes = models.CharField(max_length=255, blank=True)

    subtotal = models.BigIntegerField(default=0)
    vat_amount = models.BigIntegerField(default=0)
    total = models.BigIntegerField(default=0)
    # The part of `total` that is items taken from neighbors (VAT included). It is on the invoice and
    # in the till, but it is NOT the shop's own sales: own sales = total - sourced_total.
    sourced_total = models.BigIntegerField(default=0)

    status = models.CharField(max_length=10, choices=STATUS_CHOICES, default=COMPLETED)
    created_by = models.ForeignKey(settings.AUTH_USER_MODEL, null=True, on_delete=models.SET_NULL, related_name="sales")
    # The cashier's name as it was when the sale was made. It keeps invoices and reports readable
    # if that user account is later deleted (created_by then becomes empty).
    created_by_name = models.CharField(max_length=150, blank=True)
    created_at = models.DateTimeField(auto_now_add=True)

    class Meta:
        ordering = ["-created_at", "-id"]

    def __str__(self):
        return self.number or f"Sale #{self.pk}"

    @property
    def cashier_name(self):
        if self.created_by_id:
            return self.created_by.display_name()
        return self.created_by_name or "Former user"

    def save(self, *args, **kwargs):
        super().save(*args, **kwargs)
        if not self.number:
            self.number = f"INV-{self.pk:06d}"
            super().save(update_fields=["number"])

    @property
    def is_split(self):
        return self.payment_method == "split"

    @property
    def own_total(self):
        """Sales of the shop's own stock (what the dashboard calls 'sales')."""
        return self.total - self.sourced_total


class SalePayment(models.Model):
    """One line of how a sale was paid, e.g. 5 000 cash + 3 000 Orange Money + 2 000 credit."""

    sale = models.ForeignKey(Sale, on_delete=models.CASCADE, related_name="payments")
    method = models.CharField(max_length=14, choices=SALE_METHODS)
    amount = models.BigIntegerField()
    reference = models.CharField("Mobile money reference", max_length=60, blank=True)

    class Meta:
        ordering = ["id"]

    def __str__(self):
        return f"{self.get_method_display()} {self.amount}"


class SaleItem(models.Model):
    sale = models.ForeignKey(Sale, on_delete=models.CASCADE, related_name="items")
    # Empty for items taken from a neighbor: they are not in our products and never touch stock.
    product = models.ForeignKey("inventory.Product", null=True, blank=True, on_delete=models.PROTECT, related_name="sale_items")
    description = models.CharField(max_length=200)
    quantity = models.PositiveIntegerField()
    unit_price = models.BigIntegerField()
    discount = models.BigIntegerField(default=0, help_text="Total discount on this line.")
    amount = models.BigIntegerField()
    # Our cost price at the time of sale, or for a neighbor item, what the neighbor charges us.
    unit_cost = models.BigIntegerField(default=0, help_text="Cost at the time of sale (for profit).")

    # --- items fetched from a neighbor ---
    is_sourced = models.BooleanField(default=False)
    neighbor = models.ForeignKey(Neighbor, null=True, blank=True, on_delete=models.PROTECT, related_name="items")
    neighbor_paid_on = models.DateField(null=True, blank=True, help_text="When the neighbor was paid. Empty = still owed.")

    def __str__(self):
        return f"{self.quantity} × {self.description}"

    @property
    def cost_total(self):
        return self.quantity * self.unit_cost

    @property
    def profit(self):
        """Selling amount minus cost. Negative = a loss."""
        return self.amount - self.cost_total


class DiscountRequest(models.Model):
    """A cashier asked for a lower price; the boss must confirm before the sale."""

    PENDING = "pending"
    APPROVED = "approved"
    DECLINED = "declined"
    EXPIRED = "expired"
    STATUS_CHOICES = [
        (PENDING, "Waiting for boss"),
        (APPROVED, "Approved"),
        (DECLINED, "Declined"),
        (EXPIRED, "Expired"),
    ]

    product = models.ForeignKey("inventory.Product", on_delete=models.CASCADE, related_name="discount_requests")
    quantity = models.PositiveIntegerField(default=1)
    original_price = models.BigIntegerField()
    requested_price = models.BigIntegerField()
    reason = models.CharField(max_length=200, blank=True)
    requested_by = models.ForeignKey(settings.AUTH_USER_MODEL, null=True, on_delete=models.SET_NULL, related_name="discount_requests")
    status = models.CharField(max_length=10, choices=STATUS_CHOICES, default=PENDING)
    decided_via = models.CharField(max_length=30, blank=True)
    decided_at = models.DateTimeField(null=True, blank=True)
    consumed = models.BooleanField(default=False, help_text="Already used on a sale.")
    created_at = models.DateTimeField(auto_now_add=True)
    expires_at = models.DateTimeField()

    class Meta:
        ordering = ["-created_at"]

    def __str__(self):
        return f"{self.product.name}: {self.original_price} -> {self.requested_price} ({self.status})"

    @property
    def discount_each(self):
        return self.original_price - self.requested_price

    @property
    def percent(self):
        return round(self.discount_each * 100 / self.original_price, 1) if self.original_price else 0

    def refresh(self):
        """Marks the request expired if the boss didn't answer in time."""
        if self.status == self.PENDING and timezone.now() >= self.expires_at:
            self.status = self.EXPIRED
            self.save(update_fields=["status"])
        return self.status
